export const dashboardMessages: DashboardLocaleValues<DashboardMessages> = {
    en: englishMessages,
    nl: dutchMessages,
};

export function formatDashboardMessage(
    locale: DashboardLocale,
    key: DashboardMessageKey,
    values?: Record<string, string | number>,
): string {
    const message = dashboardMessages[locale][key] ?? dashboardMessages[defaultDashboardLocale][key];
    if (!values) return message;
    return message.replace(/\{([A-Za-z0-9_]+)\}/g, (token, name: string) => values[name] === undefined ? token : String(values[name]));
}
